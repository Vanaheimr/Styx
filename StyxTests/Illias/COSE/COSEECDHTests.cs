        [TestCaseSource(nameof(Vectors))]
        public void Every_example_holds_at_every_step(String Name)
        {

            var vector     = vectors.Single(each => each.Name == Name);
            var curve      = COSECurve.Parse(vector.Curve);
            var content    = ContentAlgorithm(vector.Content);
            var algorithm  = RecipientAlgorithm(vector.Recipient);
            var recipient  = PrivateKey(curve, Convert.FromHexString(vector.D), Convert.FromHexString(vector.KID));
            var ephemeral  = PrivateKey(curve, Convert.FromHexString(vector.Ephemeral));
            var plaintext  = Convert.FromHexString(vector.Plaintext);
            var publicKey  = PublicKeyOf(recipient);

            // The recipient key it says it has.
            Assert.That(Convert.ToHexString(recipient.X!),  Is.EqualTo(vector.X));

            if (vector.Y is not null)
                Assert.That(Convert.ToHexString(recipient.Y!),  Is.EqualTo(vector.Y));

            // The published secret, from either side.
            Assert.That(Convert.ToHexString(COSEKeyAgreement.SharedSecret(ephemeral, publicKey)),               Is.EqualTo(vector.Secret));
            Assert.That(Convert.ToHexString(COSEKeyAgreement.SharedSecret(recipient, PublicKeyOf(ephemeral))),  Is.EqualTo(vector.Secret));

            // The published COSE_KDF_Context: what the key is FOR, and its
            // length in bits.
            var direct    = algorithm.Family == COSEAlgorithmFamily.ECDHDirect;
            var forWhat   = direct ? content : COSEAlgorithm.ForKeyWrap(algorithm.KeySizeInBytes!.Value);
            var keyLength = direct ? Convert.FromHexString(vector.CEK).Length : algorithm.KeySizeInBytes!.Value;

            Assert.That(Convert.ToHexString(COSEKeyAgreement.KDFContext(forWhat, keyLength, COSEHeaders.Create(algorithm).ToProtectedByteArray())),
                        Is.EqualTo(vector.Context));

            // The published message, byte for byte.
            COSEKey        contentKey;
            COSERecipient  structure;

            if (direct)
            {

                (structure, contentKey) = COSERecipient.ECDHDirect(publicKey, ephemeral, content, algorithm);

                Assert.That(Convert.ToHexString(contentKey.K!),  Is.EqualTo(vector.CEK));

            }
            else
            {

                contentKey = COSEKey.FromSymmetricKey(Convert.FromHexString(vector.CEK), null, content);
                structure  = COSERecipient.ECDHKeyWrap(Convert.FromHexString(vector.CEK), publicKey, ephemeral, algorithm);

            }

            var written = vector.Message == "COSE_Encrypt"
                              ? COSEEncrypt.Encrypt(plaintext, contentKey, [structure], Convert.FromHexString(vector.IV!)).ToByteArray()
                              : COSEMac.    Create (plaintext, contentKey, [structure]).ToByteArray();

            Assert.That(Convert.ToHexString(written),  Is.EqualTo(vector.CBOR));

            // The published bytes, opened with the recipient's private key -
            // and with nothing else.
            var stranger = PrivateKey(curve, Convert.FromHexString(vector.Ephemeral));

            if (vector.Message == "COSE_Encrypt")
            {

                Assert.That(COSEEncrypt.TryParse(Convert.FromHexString(vector.CBOR), out var message, out var parseError),  Is.True, parseError);

                Assert.That(message!.Decrypt(recipient, out var decrypted, out var errorResponse),  Is.True, errorResponse);
                Assert.That(Convert.ToHexString(decrypted!),                                          Is.EqualTo(vector.Plaintext));
                Assert.That(message.Decrypt(publicKey, out _, out _),                                 Is.False);
                Assert.That(message.Decrypt(stranger,  out _, out _),                                 Is.False);

            }
            else
            {

                Assert.That(COSEMac.TryParse(Convert.FromHexString(vector.CBOR), out var message, out var parseError),  Is.True, parseError);

                Assert.That(message!.Verify(recipient, out var errorResponse),  Is.True, errorResponse);
                Assert.That(message.Verify(publicKey, out _),                    Is.False);
                Assert.That(message.Verify(stranger,  out _),                    Is.False);

            }

        }


