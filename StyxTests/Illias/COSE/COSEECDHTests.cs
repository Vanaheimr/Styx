        /// <summary>The examples' algorithm names, which are the JOSE-style ones of their generator.</summary>
        private static COSEAlgorithm ContentAlgorithm(String Name)

            => Name switch {
                   "A128GCM" => COSEAlgorithm.A128GCM,
                   "A256GCM" => COSEAlgorithm.A256GCM,
                   "HS512"   => COSEAlgorithm.HMAC512_512,
                   _         => throw new ArgumentException($"Unknown content algorithm '{Name}'!")
               };

        private static COSEAlgorithm RecipientAlgorithm(String Name)

            => Name switch {
                   "ECDH-ES"        => COSEAlgorithm.ECDH_ES_HKDF_256,
                   "ECDH-ES-512"    => COSEAlgorithm.ECDH_ES_HKDF_512,
                   "ECDH-ES-A128KW" => COSEAlgorithm.ECDH_ES_A128KW,
                   "ECDH-ES-A192KW" => COSEAlgorithm.ECDH_ES_A192KW,
                   "ECDH-ES-A256KW" => COSEAlgorithm.ECDH_ES_A256KW,
                   _                => throw new ArgumentException($"Unknown recipient algorithm '{Name}'!")
               };

        /// <summary>
        /// A private key on the given curve from its raw private key, as a
        /// complete key pair: an EC2 scalar or an X25519/X448 private key.
        /// </summary>
        private static COSEKey PrivateKey(COSECurve Curve, Byte[] D, Byte[]? KeyIdentifier = null)

            => Curve == COSECurve.X25519 ? COSEKey.From(new X25519PrivateKeyParameters(D, 0), KeyIdentifier)
             : Curve == COSECurve.X448   ? COSEKey.From(new X448PrivateKeyParameters  (D, 0), KeyIdentifier)
             :                             COSEKey.From(new ECPrivateKeyParameters("ECDH", new BigInteger(1, D), Curve.DomainParameters!), KeyIdentifier);

        private static COSEKey PublicKeyOf(COSEKey Key)

            => COSEKey.From(Key.ToPublicKey(), Key.KeyIdentifier);

        private static COSEKey Alice => PrivateKey(COSECurve.X25519, aliceX25519);
        private static COSEKey Bob   => PrivateKey(COSECurve.X25519, bobX25519);

